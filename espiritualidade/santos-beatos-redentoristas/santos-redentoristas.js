const normalize=s=>(s||"").normalize("NFD").replace(/[\u0300-\u036f]/g,"").toLowerCase();
const list=document.querySelector("#saints-list");
const search=document.querySelector("#saints-search-input");
const statusFilter=document.querySelector("#saints-status-filter");
const monthFilter=document.querySelector("#saints-month-filter");
const count=document.querySelector("#saints-count");
const empty=document.querySelector("#saints-empty");
const clear=document.querySelector("#saints-clear");

function card(r,i){
  const id="redentorista-"+i;
  return `<article class="saint-card" id="${id}">
    <p class="saint-status">${r.status}</p>
    <h3>${r.name}</h3>
    <p class="saint-meta"><span>${r.years||""}</span>${r.country?`<span>${r.country}</span>`:""}</p>
    ${r.memory?`<p class="saint-detail"><strong>Memória / festa:</strong> ${formatDate(r.memory)}</p>`:""}
    ${r.beat?`<p class="saint-detail"><strong>Beatificação:</strong> ${r.beat}</p>`:""}
    ${r.canon?`<p class="saint-detail"><strong>Canonização:</strong> ${r.canon}</p>`:""}
    ${r.note?`<p class="saint-note">${r.note}</p>`:""}
  </article>`;
}
function formatDate(md){
  const [d,m]=md.split("/");
  const months=["","janeiro","fevereiro","março","abril","maio","junho","julho","agosto","setembro","outubro","novembro","dezembro"];
  return Number(d)+" de "+months[Number(m)];
}
function render(){
  const q=normalize(search?.value);
  const s=statusFilter?.value||"";
  const m=monthFilter?.value||"";
  const filtered=redemptorists.filter(r=>{
    const matchesText=!q||normalize(r.name+" "+r.country+" "+(r.note||"")).includes(q);
    const matchesStatus=!s||r.status===s;
    const matchesMonth=!m||(r.memory&&r.memory.slice(3)===m);
    return matchesText&&matchesStatus&&matchesMonth;
  });
  if(list) list.innerHTML=filtered.map(r=>card(r,redemptorists.indexOf(r))).join("");
  if(count) count.textContent=filtered.length+" "+(filtered.length===1?"registro":"registros");
  if(empty) empty.hidden=filtered.length!==0;
}
[search,statusFilter,monthFilter].forEach(el=>el?.addEventListener(el===search?"input":"change",render));
clear?.addEventListener("click",()=>{if(search)search.value="";if(statusFilter)statusFilter.value="";if(monthFilter)monthFilter.value="";render();});
document.querySelectorAll("[data-filter-link]").forEach(a=>a.addEventListener("click",()=>{if(statusFilter)statusFilter.value=a.dataset.filterLink||"";if(monthFilter)monthFilter.value="";if(search)search.value="";render();}));

const monthNames=["","Janeiro","Fevereiro","Março","Abril","Maio","Junho","Julho","Agosto","Setembro","Outubro","Novembro","Dezembro"];
const calendar=document.querySelector("#saints-calendar-list");
if(calendar){
  const groups={};
  redemptorists.filter(r=>r.memory).forEach(r=>{
    const [d,m]=r.memory.split("/");
    (groups[m]??=[]).push({r,d});
  });
  calendar.innerHTML=Object.keys(groups).sort().map(m=>{
    const items=groups[m].sort((a,b)=>Number(a.d)-Number(b.d)).map(({r,d})=>{
      const i=redemptorists.indexOf(r);
      return `<li><span class="calendar-date">${Number(d)}</span><a href="#redentorista-${i}">${r.name}</a></li>`;
    }).join("");
    return `<section class="calendar-month"><h3>${monthNames[Number(m)]}</h3><ul>${items}</ul></section>`;
  }).join("");
}
render();
